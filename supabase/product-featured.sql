-- ============================================================
--  Приоритетный товар (Featured / Priority Product)
--  Такие товары поднимаются выше в результатах поиска.
--  Запустить в Supabase → SQL Editor → New query → Run
-- ============================================================

-- 1) Новая колонка-флаг. Значение по умолчанию false, NOT NULL —
--    существующие товары автоматически станут обычными (не приоритетными).
alter table public.products
  add column if not exists is_featured boolean not null default false;

-- 2) (Опционально) частичный индекс — ускоряет выборку приоритетных,
--    если товаров станет много. Безопасно даже на маленькой базе.
create index if not exists products_is_featured_idx
  on public.products (is_featured)
  where is_featured = true;

-- Примечание:
--   RLS не меняется — колонка читается вместе с остальными полями (select *),
--   пишется только из админки (существующая политика на update/insert для
--   аутентифицированного владельца). Никаких новых политик не требуется.
